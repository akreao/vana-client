"""Generates gearshift/src/build/blu.lua: blue magic by spell id, its kind as LandSandBoat's script casts it (phys,
magic, debuff, breath, heal, drain, buff). Facts from sql/spell_list.sql and scripts/actions/spells/blue/*.lua.
   python3 -I crates/vana-client/data/gearshift_blu_gen.py LSB_DIR crates/vana-client/assets/mods/gearshift/src/build/blu.lua"""
import os, re, sys
lsb, out = sys.argv[1], sys.argv[2]
ids = {}
for m in re.finditer(r"INSERT INTO `spell_list` VALUES \((\d+),'([a-z0-9_]+)'", open(os.path.join(lsb, "sql/spell_list.sql")).read()):
    ids[m.group(2)] = int(m.group(1))
KINDS = [("phys", "usePhysicalSpell"), ("magic", "useMagicalSpell"), ("debuff", "useEnfeeblingSpell"),
         ("breath", "useBreathSpell"), ("heal", "useCuringSpell"), ("drain", "useDrainSpell")]
d = os.path.join(lsb, "scripts/actions/spells/blue")
rows = []
for f in sorted(os.listdir(d)):
    name = f[:-4]
    if name not in ids:
        continue
    src = open(os.path.join(d, f)).read()
    kind = next((k for k, fn in KINDS if fn in src), "buff")
    rows.append((ids[name], kind, name))
lines = ["-- Generated by crates/vana-client/data/gearshift_blu_gen.py from a LandSandBoat checkout: blue magic by spell id, its kind as the server casts it.",
         "-- Facts only; regenerate instead of editing.", "return {"]
lines += ['  [%d] = "%s", -- %s' % r for r in sorted(rows)]
lines.append("}")
open(out, "w").write("\n".join(lines) + "\n")
print(len(rows), "blue spells")
