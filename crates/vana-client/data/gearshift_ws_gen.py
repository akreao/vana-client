"""Generates gearshift/src/build/ws.lua: per weapon skill id, its kind (phys / ranged / magic / breath), stat
modifiers (Adoulin values where the script has them), element (magical ones) and skillchain properties. Facts read
from a LandSandBoat checkout (data/weapon_skills.yaml, scripts/actions/weaponskills/*.lua).
   python3 -I crates/vana-client/data/gearshift_ws_gen.py LSB_DIR crates/vana-client/assets/mods/gearshift/src/build/ws.lua"""
import os, re, sys, yaml

lsb, out = sys.argv[1], sys.argv[2]
data = yaml.safe_load(open(os.path.join(lsb, "data/weapon_skills.yaml")))["weapon_skills"]
ATTR = ["str", "dex", "vit", "agi", "int", "mnd", "chr"]


def script_facts(name):
    p = os.path.join(lsb, "scripts/actions/weaponskills", name + ".lua")
    if not os.path.exists(p):
        return None
    src = open(p).read()
    kind = None
    for k, fn in [("magic", "doMagicWeaponskill"), ("ranged", "doRangedWeaponskill"), ("breath", "doBreathWeaponskill"),
                  ("phys", "doPhysicalWeaponskill")]:
        if fn in src:
            kind = k
            break
    mods = {}
    # The first assignment of each modifier, then the Adoulin block's (they come after it in the script).
    for a in ATTR:
        for m in re.finditer(r"params\.%s_wsc\s*=\s*([0-9.]+)" % a, src):
            mods[a] = round(float(m.group(1)) * 100)
    mods = {k: v for k, v in mods.items() if v}
    ele = re.search(r"params\.ele\s*=\s*xi\.element\.([A-Z]+)", src)
    return kind, mods, ele.group(1).lower() if ele else None


lines = ["-- Generated by crates/vana-client/data/gearshift_ws_gen.py from a LandSandBoat checkout (data/weapon_skills.yaml and the weapon skill scripts):",
         "-- per weapon skill id {kind, skill (weapon type), stat modifiers in percent, element, jobs, skillchain properties}.",
         "-- Facts only; regenerate instead of editing.", "return {"]
for name, w in sorted(data.items(), key=lambda kv: kv[1]["id"]):
    f = script_facts(name)
    if not f or not f[0]:
        continue
    kind, mods, ele = f
    parts = ['kind = "%s"' % kind, 'skill = "%s"' % w.get("skill", "")]
    if mods:
        parts.append("mods = { %s }" % ", ".join("%s = %d" % (k, mods[k]) for k in ATTR if k in mods))
    if ele:
        parts.append('element = "%s"' % ele)
    jobs = w.get("jobs") or []
    if jobs:
        parts.append('jobs = "%s"' % ",".join(j.upper() for j in jobs))
    sc = w.get("skillchain") or []
    if sc:
        parts.append("sc = { %s }" % ", ".join('"%s"' % s for s in sc))
    lines.append("  [%d] = { %s }, -- %s" % (w["id"], ", ".join(parts), name))
lines.append("}")
open(out, "w").write("\n".join(lines) + "\n")
print(len(lines) - 5, "weapon skills")
